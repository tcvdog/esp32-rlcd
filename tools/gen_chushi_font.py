#!/usr/bin/env python3
"""Generate a 20px 1bpp glyph subset for 出师表 (Noto Serif CJK SC Bold)."""
import ast, re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

h = Path('game_proto/main/chushi_cards.h').read_text()
m = re.search(r'CHUSHI_ORIGINAL\[\] = (".*?");', h, re.S)
text = ast.literal_eval(m.group(1))
chars = sorted(set(text) | {'○'})
font = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc', 20,
                          index=2, layout_engine=ImageFont.Layout.BASIC)
glyphs, blob = [], bytearray()
for ch in chars:
    cp = ord(ch)
    bbox = font.getbbox(ch)
    w = min(max(1, bbox[2] - bbox[0]), 24)
    hh = min(max(1, bbox[3] - bbox[1]), 24)
    img = Image.new('L', (w, hh), 0)
    ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
    rowbytes = (w + 7) // 8
    off = len(blob)
    for y in range(hh):
        for bx in range(rowbytes):
            v = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < w and img.getpixel((x, y)) > 110:
                    v |= 1 << bit  # U8g2 XBM is LSB-first
            blob.append(v)
    glyphs.append((cp, w, hh, off))

out = ['#pragma once', '',
       '// 20px Noto Serif CJK SC Bold subset for 出师表. Generated by tools/gen_chushi_font.py.',
       '#include <stdint.h>', '',
       'struct ClozeGlyph { uint32_t cp; uint8_t w; uint8_t h; uint16_t off; };', '']
out.append(f'static const int CLOZE_GLYPH_COUNT = {len(glyphs)};')
out.append('static const ClozeGlyph CLOZE_GLYPHS[] = {')
for cp, w, hh, off in glyphs:
    out.append(f'    {{0x{cp:04X}, {w}, {hh}, {off}}},')
out.append('};')
out.append('')
out.append(f'static const uint8_t CLOZE_GLYPH_BITS[{len(blob)}] = {{')
for i in range(0, len(blob), 24):
    out.append('    ' + ','.join(f'0x{b:02X}' for b in blob[i:i+24]) + ',')
out.append('};')
Path('game_proto/main/chushi_font20.h').write_text('\n'.join(out) + '\n')
print('glyphs', len(glyphs), 'bytes', len(blob))
