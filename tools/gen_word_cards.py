#!/usr/bin/env python3
"""Generate the firmware word-card table and the printable study sheet.

Source of truth: data/ket_pet_words.tsv
Outputs:
  game_proto/main/word_cards.h
  docs/ket-pet-100.md

The script validates coverage before writing anything:
  * exactly 6 BASE cards and 100 KET/PET cards (50 + 50)
  * every sentence contains its own target word
  * every Chinese string is GB2312 encodable (u8g2 wqy font coverage)
  * sentence length fits the two-line card layout
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TSV = ROOT / "data" / "ket_pet_words.tsv"
HEADER = ROOT / "game_proto" / "main" / "word_cards.h"
DOC = ROOT / "docs" / "ket-pet-100.md"

MAX_SENTENCE = 84


def load_rows():
    with TSV.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    return rows


def validate(rows):
    errors = []
    levels = [r["level"] for r in rows]
    if levels.count("BASE") != 6:
        errors.append(f"expected 6 BASE cards, got {levels.count('BASE')}")
    if levels.count("KET") != 100:
        errors.append(f"expected 100 KET cards, got {levels.count('KET')}")
    if levels.count("PET") != 100:
        errors.append(f"expected 100 PET cards, got {levels.count('PET')}")
    if len(rows) != 206:
        errors.append(f"expected 206 rows, got {len(rows)}")

    seen = set()
    for i, r in enumerate(rows, 1):
        word = r["word"]
        if word in seen:
            errors.append(f"row {i}: duplicate word {word!r}")
        seen.add(word)
        if not re.fullmatch(r"[a-z]+", word):
            errors.append(f"row {i}: word must be lowercase ASCII letters: {word!r}")
        # Allow normal inflections: plays/played/playing, arrives/arrived, etc.
        if not re.search(r"\b" + re.escape(word) + r"(?:s|es|ed|d|ing)?\b", r["sentence"], re.I):
            errors.append(f"row {i}: sentence does not contain {word!r}")
        if len(r["sentence"]) > MAX_SENTENCE:
            errors.append(f"row {i}: sentence too long ({len(r['sentence'])} > {MAX_SENTENCE})")
        for field in ("zh", "sentence_zh"):
            try:
                r[field].encode("gb2312")
            except UnicodeEncodeError as exc:
                errors.append(f"row {i}: {field} not GB2312 encodable: {exc}")
        if any(ord(c) > 127 for c in r["sentence"]):
            errors.append(f"row {i}: English sentence contains non-ASCII characters")

    targets = [r["word"] for r in rows if r["level"] in ("KET", "PET")]
    corpus = " ".join(r["sentence"].lower() for r in rows)
    missing = [w for w in targets if not re.search(r"\b" + re.escape(w) + r"(?:s|es|ed|d|ing)?\b", corpus)]
    if missing:
        errors.append(f"target words missing from sentences: {missing}")
    return errors


def c_quote(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_header(rows):
    lines = [
        "// Auto-generated by tools/gen_word_cards.py from data/ket_pet_words.tsv.",
        "// Do not edit by hand; run: python3 tools/gen_word_cards.py",
        "#pragma once",
        "",
        "struct WordCard {",
        "    const char *en;",
        "    const char *zh;",
        "    const char *level;",
        "    const char *sentence;",
        "    const char *sentence_zh;",
        "};",
        "",
        "static const WordCard WORD_CARDS[] = {",
    ]
    for r in rows:
        lines.append(
            '    { "%s", "%s", "%s", "%s", "%s" },'
            % tuple(c_quote(r[k]) for k in ("word", "zh", "level", "sentence", "sentence_zh"))
        )
    lines += [
        "};",
        f"static constexpr int WORD_COUNT = {len(rows)};",
        f"static constexpr int KET_PET_COUNT = {sum(r['level'] in ('KET', 'PET') for r in rows)};",
        "",
    ]
    HEADER.write_text("\n".join(lines), encoding="utf-8")


def md_row(i, r):
    return "| %d | %s | %s | %s | %s |" % (
        i, r["word"], r["zh"], r["sentence"], r["sentence_zh"]
    )


def write_doc(rows):
    ket = [r for r in rows if r["level"] == "KET"]
    pet = [r for r in rows if r["level"] == "PET"]
    base = [r for r in rows if r["level"] == "BASE"]
    out = [
        "# KET / PET 各 100 词 + 200 句覆盖清单",
        "",
        "本清单与 ESP32 单词卡固件共用同一份数据（`data/ket_pet_words.tsv`），",
        "由 `tools/gen_word_cards.py` 自动生成，词条和例句不会互相脱节。",
        "",
        "## 覆盖情况",
        "",
        f"- 新增 KET/PET 单词：**{len(ket) + len(pet)}** 个（KET {len(ket)} + PET {len(pet)}）",
        "- 例句：**100** 句，每句都包含对应的目标单词",
        "- 100 个新增词全部被例句覆盖（构建脚本逐条校验）",
        f"- 另保留 {len(base)} 张基础复习卡（apple / banana / cat / dog / book / water），不计入 100",
        "",
        "## 用法建议",
        "",
        "1. 先读英文单词，自己造一个句子，再按 **A** 看中文释义。",
        "2. 读例句时遮住译文，确认自己理解整句，而不是只认识目标词。",
        "3. 左右键顺序复习；一天 10 词，10 天完成一轮 KET/PET 新增词。",
        "4. 第二轮只看例句，尝试说出目标词的中文意思。",
        "",
        "## KET 50 词",
        "",
        "| # | 单词 | 中文 | 例句 | 译文 |",
        "|---|---|---|---|---|",
    ]
    for i, r in enumerate(ket, 1):
        out.append(md_row(i, r))
    out += [
        "",
        "## PET 50 词",
        "",
        "| # | 单词 | 中文 | 例句 | 译文 |",
        "|---|---|---|---|---|",
    ]
    for i, r in enumerate(pet, 51):
        out.append(md_row(i, r))
    out += [
        "",
        "## 基础复习卡（6）",
        "",
        "| 单词 | 中文 | 例句 | 译文 |",
        "|---|---|---|---|",
    ]
    for r in base:
        out.append("| %s | %s | %s | %s |" % (r["word"], r["zh"], r["sentence"], r["sentence_zh"]))
    out += [
        "",
        "---",
        "",
        "数据源：`data/ket_pet_words.tsv`；固件表：`game_proto/main/word_cards.h`。",
        "",
    ]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(out), encoding="utf-8")


def main():
    rows = load_rows()
    errors = validate(rows)
    if errors:
        print("validation failed:", file=sys.stderr)
        for e in errors:
            print(" -", e, file=sys.stderr)
        return 1
    write_header(rows)
    write_doc(rows)
    print(f"wrote {HEADER.relative_to(ROOT)} ({len(rows)} cards)")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
