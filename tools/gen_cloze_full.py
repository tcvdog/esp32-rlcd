def parse_cards(path, names):
    s=Path(path).read_text(); out=[]
    for name in names:
        m=re.search(r'static const PoemCard '+name+r'\[\] = \{(.*?)\n\};', s, re.S)
        if not m: continue
        pat=re.compile(r'\{"([^"]*)",\s*"([^"]*)",\s*\{(.*?)\},\s*"([^"]*)",\s*(\d+)\}')
        for a,b,ln,n,k in pat.findall(m.group(1)):
            out.append((a,b,re.findall(r'"([^"]*)"',ln)))
    return out

