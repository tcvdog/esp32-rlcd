#!/usr/bin/env python3
"""Generate word-level cloze levels for 出师表.

Rule: mask whole words only (jieba), never split a word; keep punctuation,
whitespace and paragraph breaks; leave at least one content-word anchor per
sentence for L1-L4.
"""
import json
import random
from pathlib import Path

TEXT = """先帝创业未半而中道崩殂，今天下三分，益州疲弊，此诚危急存亡之秋也。然侍卫之臣不懈于内，忠志之士忘身于外者，盖追先帝之殊遇，欲报之于陛下也。诚宜开张圣听，以光先帝遗德，恢弘志士之气，不宜妄自菲薄，引喻失义，以塞忠谏之路也。

宫中府中，俱为一体，陟罚臧否，不宜异同。若有作奸犯科及为忠善者，宜付有司论其刑赏，以昭陛下平明之理，不宜偏私，使内外异法也。

侍中、侍郎郭攸之、费祎、董允等，此皆良实，志虑忠纯，是以先帝简拔以遗陛下。愚以为宫中之事，事无大小，悉以咨之，然后施行，必能裨补阙漏，有所广益。

将军向宠，性行淑均，晓畅军事，试用于昔日，先帝称之曰能，是以众议举宠为督。愚以为营中之事，悉以咨之，必能使行阵和睦，优劣得所。

亲贤臣，远小人，此先汉所以兴隆也；亲小人，远贤臣，此后汉所以倾颓也。先帝在时，每与臣论此事，未尝不叹息痛恨于桓、灵也。侍中、尚书、长史、参军，此悉贞良死节之臣，愿陛下亲之信之，则汉室之隆，可计日而待也。

臣本布衣，躬耕于南阳，苟全性命于乱世，不求闻达于诸侯。先帝不以臣卑鄙，猥自枉屈，三顾臣于草庐之中，咨臣以当世之事，由是感激，遂许先帝以驱驰。后值倾覆，受任于败军之际，奉命于危难之间，尔来二十有一年矣。

先帝知臣谨慎，故临崩寄臣以大事也。受命以来，夙夜忧叹，恐托付不效，以伤先帝之明，故五月渡泸，深入不毛。今南方已定，兵甲已足，当奖率三军，北定中原，庶竭驽钝，攘除奸凶，兴复汉室，还于旧都。此臣所以报先帝而忠陛下之职分也。至于斟酌损益，进尽忠言，则攸之、祎、允之任也。

愿陛下托臣以讨贼兴复之效，不效，则治臣之罪，以告先帝之灵。若无兴德之言，则责攸之、祎、允等之慢，以彰其咎。陛下亦宜自谋，以咨诹善道，察纳雅言，深追先帝遗诏。臣不胜受恩感激。

今当远离，临表涕零，不知所言。"""

PUNCT = set("，。；：！？、\n “”《》")
STOP = set("的了和在有把被并且于以之为其而则也矣焉哉乎兮所与因若虽然故乃遂")

def is_cjk(ch):
    return '\u4e00' <= ch <= '\u9fff'

def is_punct(ch):
    return ch in PUNCT or ch.isspace()

def token_spans(text):
    import jieba
    spans = []
    pos = 0
    for w in jieba.lcut(text):
        spans.append((w, pos, pos + len(w)))
        pos += len(w)
    assert pos == len(text)
    return spans

def mask_level(text, spans, level):
    pct = {1: .20, 2: .40, 3: .60, 4: .80, 5: 1.0}[level]
    # Group token indices into sentences.
    sentences, cur = [], []
    for ti, (w, a, b) in enumerate(spans):
        if all(is_punct(c) for c in w):
            if cur:
                sentences.append(cur); cur = []
        else:
            cur.append(ti)
    if cur: sentences.append(cur)
    mask = [False] * len(text)
    content_total = sum(1 for c in text if is_cjk(c))
    if level == 5:
        for i, c in enumerate(text):
            if is_cjk(c): mask[i] = True
        return mask
    target = int(content_total * pct)
    rng = random.Random(level * 7919)
    anchors = set()
    candidates = []
    for sent in sentences:
        anchor = None
        for ti in sent:
            w, a, b = spans[ti]
            if any(is_cjk(c) for c in w):
                anchor = ti; break
        if anchor is not None: anchors.add(anchor)
        for ti in sent:
            if level < 3 and ti == anchor: continue
            w, a, b = spans[ti]
            cjk = [c for c in w if is_cjk(c)]
            if not cjk: continue
            if level < 3 and len(cjk) > 4: continue
            if level < 3 and all(c in STOP for c in cjk): continue
            if any(is_punct(c) for c in w): continue
            candidates.append(ti)
    # Distribute masks over 8 text bands so every page has some blanks.
    BANDS = 8
    by_band = [[] for _ in range(BANDS)]
    for ti in candidates:
        _, a, b = spans[ti]
        band = min(BANDS - 1, a * BANDS // max(1, len(text)))
        by_band[band].append(ti)
    selected = set()
    total = 0
    for band in range(BANDS):
        rng.shuffle(by_band[band])
        band_target = target // BANDS + (1 if band < target % BANDS else 0)
        band_count = 0
        for ti in by_band[band]:
            if ti in selected: continue
            if level < 3 and ((ti - 1) in selected or (ti + 1) in selected): continue
            _, a, b = spans[ti]
            n = sum(1 for i in range(a, b) if is_cjk(text[i]))
            if band_count > 0 and band_count + n > band_target + 4: continue
            selected.add(ti)
            band_count += n
            total += n
            if band_count >= band_target: break
    # If bands were too sparse, fill from global candidates.
    if total < target:
        for ti in candidates:
            if ti in selected: continue
            if level < 3 and ((ti - 1) in selected or (ti + 1) in selected): continue
            _, a, b = spans[ti]
            n = sum(1 for i in range(a, b) if is_cjk(text[i]))
            selected.add(ti); total += n
            if total >= target: break
    for ti in selected:
        w, a, b = spans[ti]
        for i in range(a, b):
            if is_cjk(text[i]): mask[i] = True
    return mask

def render(text, mask):
    out = []
    for c, m in zip(text, mask):
        if m:
            out.append('○' if is_cjk(c) else '_')
        else:
            out.append(c)
    return ''.join(out)

text = TEXT
spans = token_spans(text)
levels = [render(text, mask_level(text, spans, i)) for i in range(1, 6)]
for s in levels:
    assert len(s) == len(text)
# Header
hdr = '#pragma once\n\n// Generated by tools/gen_chushi.py (jieba, whole-word masking).\n'
hdr += '// Character positions, punctuation and paragraph breaks are preserved.\n\n'
hdr += 'static const char CHUSHI_ORIGINAL[] = ' + json.dumps(text, ensure_ascii=False) + ';\n\n'
hdr += 'static const char *CHUSHI_LEVELS[5] = {\n'
for s in levels:
    hdr += '    ' + json.dumps(s, ensure_ascii=False) + ',\n'
hdr += '};\n'
Path('game_proto/main/chushi_cards.h').write_text(hdr)
print('chars', len(text))
for i, s in enumerate(levels, 1):
    print(i, 'masked', s.count('○'), f'{s.count("○")/sum(1 for c in text if is_cjk(c))*100:.1f}%')
